#!/usr/bin/env node
/**
 * Build script: reads src/injection/ucore_injector.js and
 * generates src/injection/ucore.js with the content as an exported string.
 *
 * Run: node scripts/embed-ucore.js
 * Or automatically via: npm run prebuild
 */

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '../src/injection/ucore_injector.js');
const OUT = path.join(__dirname, '../src/injection/ucore.js');

const raw = fs.readFileSync(SRC, 'utf8');

// Use JSON.stringify to safely escape all special chars including backticks
const escaped = JSON.stringify(raw);

const output = `// AUTO-GENERATED — run: node scripts/embed-ucore.js
// ツcore v3.17.0 injector, embedded as a safe string.
// Do not edit this file directly; edit ucore_injector.js instead.

export const UCORE_SCRIPT = ${escaped};
`;

fs.writeFileSync(OUT, output, 'utf8');
console.log(`[embed-ucore] Written ${output.length} bytes to ${OUT}`);
